-- Esquema de la base de datos del Sistema de Préstamos/Biblioteca.
-- Se puede ejecutar varias veces: borra las tablas existentes y las vuelve a crear.
-- Uso (un comando por archivo):
--   mysql -u root -p biblioteca_db -e "source database/schema.sql"
--   mysql -u root -p biblioteca_db -e "source database/seed.sql"

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS LIBROS_PRESTADOS, PRESTAMOS, LIBROS_has_CATEGORIAS, AUTORES_has_LIBROS,
    USUARIOS, LIBROS, AUTORES, CATEGORIAS, CARGO, ESTADO_PRESTAMOS, NACIONALIDAD, CLIENTES,
    EDITORIAL;
SET FOREIGN_KEY_CHECKS = 1;

-- Tablas independientes / catálogos
CREATE TABLE EDITORIAL (
    EDITORIAL_ID CHAR(4) NOT NULL,
    NOMBRE VARCHAR(70) NOT NULL,
    PRIMARY KEY (EDITORIAL_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Clientes de la biblioteca. Si PASSWORD es NULL, el cliente no puede entrar al portal.
-- Inician sesión con su CORREO.
CREATE TABLE CLIENTES (
    CLIENTE_ID CHAR(4) NOT NULL,
    NOMBRE VARCHAR(50) NOT NULL,
    APELLIDO_P VARCHAR(30) NOT NULL,
    APELLIDO_M VARCHAR(30) NULL,
    CORREO VARCHAR(50) NOT NULL UNIQUE,
    TELEFONO VARCHAR(20) NULL,
    PASSWORD VARCHAR(255) NULL,
    PRIMARY KEY (CLIENTE_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE NACIONALIDAD (
    NACIONALIDAD_ID CHAR(4) NOT NULL,
    NOMBRE VARCHAR(20) NOT NULL,
    PRIMARY KEY (NACIONALIDAD_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE ESTADO_PRESTAMOS (
    ESTADO_PRESTAMOS_ID CHAR(4) NOT NULL,
    ESTADO VARCHAR(20) NOT NULL,
    PRIMARY KEY (ESTADO_PRESTAMOS_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE CARGO (
    CARGO_ID CHAR(4) NOT NULL,
    PUESTO VARCHAR(20) NOT NULL,
    PRIMARY KEY (CARGO_ID),
    CONSTRAINT CHK_Puesto CHECK (PUESTO IN ('BIBLIOTECARIO', 'ADMINISTRADOR'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE CATEGORIAS (
    CATEGORIA_ID CHAR(4) NOT NULL,
    NOMBRE_CATEGORIA VARCHAR(30) NOT NULL,
    PRIMARY KEY (CATEGORIA_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Tablas con llaves foráneas directas
CREATE TABLE AUTORES (
    AUTOR_ID CHAR(4) NOT NULL,
    NACIONALIDAD_ID CHAR(4) NOT NULL,
    NOMBRE_AUTOR VARCHAR(50) NOT NULL,
    APELLIDO_P VARCHAR(20) NOT NULL,
    APELLIDO_M VARCHAR(20) NULL,
    PRIMARY KEY (AUTOR_ID),
    CONSTRAINT FK_AUTOR_NACIONALIDAD FOREIGN KEY (NACIONALIDAD_ID)
        REFERENCES NACIONALIDAD (NACIONALIDAD_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Cada fila es un ejemplar físico: DISPONIBLE = FALSE mientras está apartado o prestado.
CREATE TABLE LIBROS (
    LIBRO_ID CHAR(4) NOT NULL,
    EDITORIAL_ID CHAR(4) NOT NULL,
    TITULO VARCHAR(100) NOT NULL,
    ANIO_PUBLICACION SMALLINT NULL,
    DISPONIBLE BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (LIBRO_ID),
    CONSTRAINT FK_LIBRO_EDITORIAL FOREIGN KEY (EDITORIAL_ID) REFERENCES EDITORIAL (EDITORIAL_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Personal de la biblioteca (bibliotecarios y administradores).
CREATE TABLE USUARIOS (
    USUARIO_ID CHAR(4) NOT NULL,
    CARGO_ID CHAR(4) NOT NULL,
    USERNAME VARCHAR(20) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL,
    NOMBRE VARCHAR(20) NOT NULL,
    APELLIDO_P VARCHAR(20) NOT NULL,
    APELLIDO_M VARCHAR(20) NULL,
    PRIMARY KEY (USUARIO_ID),
    CONSTRAINT FK_USUARIO_CARGO FOREIGN KEY (CARGO_ID) REFERENCES CARGO (CARGO_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Tablas intermedias (Muchos a Muchos)
CREATE TABLE AUTORES_has_LIBROS (
    AUTOR_ID CHAR(4) NOT NULL,
    LIBRO_ID CHAR(4) NOT NULL,
    PRIMARY KEY (AUTOR_ID, LIBRO_ID),
    CONSTRAINT FK_AL_AUTOR FOREIGN KEY (AUTOR_ID) REFERENCES AUTORES (AUTOR_ID),
    CONSTRAINT FK_AL_LIBROS FOREIGN KEY (LIBRO_ID) REFERENCES LIBROS (LIBRO_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE LIBROS_has_CATEGORIAS (
    CATEGORIA_ID CHAR(4) NOT NULL,
    LIBRO_ID CHAR(4) NOT NULL,
    PRIMARY KEY (CATEGORIA_ID, LIBRO_ID),
    CONSTRAINT FK_LC_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIAS (CATEGORIA_ID),
    CONSTRAINT FK_LC_LIBRO FOREIGN KEY (LIBRO_ID) REFERENCES LIBROS (LIBRO_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Préstamos y detalle.
--   FECHA_PRESTAMO:   día en que se apartó o entregó.
--   FECHA_LIMITE:     día en que vence el préstamo.
--   FECHA_DEVOLUCION: día en que el cliente regresó los libros (NULL mientras no regrese).
-- USUARIO_ID es el bibliotecario que lo atendió; queda NULL si el cliente lo apartó desde
-- el portal y todavía nadie se lo ha entregado.
-- PRESTAMO_ID es VARCHAR(10) para que la numeración no se acabe en P999.
CREATE TABLE PRESTAMOS (
    PRESTAMO_ID VARCHAR(10) NOT NULL,
    ESTADO_PRESTAMOS_ID CHAR(4) NOT NULL,
    CLIENTE_ID CHAR(4) NOT NULL,
    USUARIO_ID CHAR(4) NULL,
    FECHA_PRESTAMO DATE NOT NULL,
    FECHA_LIMITE DATE NOT NULL,
    FECHA_DEVOLUCION DATE NULL,
    PRIMARY KEY (PRESTAMO_ID),
    CONSTRAINT FK_PRESTAMO_ESTADO FOREIGN KEY (ESTADO_PRESTAMOS_ID)
        REFERENCES ESTADO_PRESTAMOS (ESTADO_PRESTAMOS_ID),
    CONSTRAINT FK_PRESTAMO_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTES (CLIENTE_ID),
    CONSTRAINT FK_PRESTAMO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (USUARIO_ID),
    CONSTRAINT CHK_FECHAS CHECK (FECHA_LIMITE >= FECHA_PRESTAMO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- PRESTADOS_ID es autoincremental: antes era CHAR(4) ('LP01') y se acababa en LP99.
CREATE TABLE LIBROS_PRESTADOS (
    PRESTADOS_ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    PRESTAMO_ID VARCHAR(10) NOT NULL,
    LIBRO_ID CHAR(4) NOT NULL,
    CANTIDAD TINYINT UNSIGNED NOT NULL DEFAULT 1,
    PRIMARY KEY (PRESTADOS_ID),
    UNIQUE KEY UQ_PRESTAMO_LIBRO (PRESTAMO_ID, LIBRO_ID),
    CONSTRAINT FK_LP_LIBRO FOREIGN KEY (LIBRO_ID) REFERENCES LIBROS (LIBRO_ID),
    CONSTRAINT FK_LP_PRESTAMO FOREIGN KEY (PRESTAMO_ID) REFERENCES PRESTAMOS (PRESTAMO_ID)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
